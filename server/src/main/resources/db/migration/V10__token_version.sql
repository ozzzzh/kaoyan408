-- 令牌版本：让「禁用账号 / 改密码 / 主动踢下线」能立刻让旧 token 失效。
--
-- 背景：JWT 是无状态的，只验签不查库时，账号被禁用、被删除、改过密码之后，
-- 手里的旧 token 仍然能一直用到过期（默认 7 天）。
--
-- 做法：签发时把 app_user.token_version 写进 claim，每次请求核对一次（带 60 秒缓存）。
-- 需要让某人的旧 token 失效时，把这一列加一即可，无需维护黑名单、也无需引入 Redis。
--
-- 现有用户统一从 1 开始：升级前签发的 token 里没有 ver 字段，会被当成 0，
-- 与数据库里的 1 不匹配 —— 也就是说**升级后所有用户需要重新登录一次**。
-- 这是有意的取舍：一次全量重新登录，换来之后每次禁用都能立即生效。
ALTER TABLE app_user ADD COLUMN token_version INT NOT NULL DEFAULT 1;
